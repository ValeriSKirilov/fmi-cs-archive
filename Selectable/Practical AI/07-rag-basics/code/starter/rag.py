def embed(texts: list[str]) -> list[list[float]]:
    """Векторизира всички текстове с една заявка. (дадено)"""
    return ollama.embed(model=EMBED_MODEL, input=texts)["embeddings"]


def retrieve(store, question: str, k: int = 4):
    """RETRIEVE: векторизира въпроса със СЪЩИЯ модел и връща k-те най-близки части. (дадено)"""
    return store.query(embed([question])[0], top_k=k)


def build_prompt(question: str, hits) -> str:
    """AUGMENT: номериран контекст [1], [2], ... и въпросът след него."""
    # TODO 2: 1) номерирайте частите от 1: "[1] текст", "[2] текст", ...
    #            (h.text е текстът на частта; enumerate(hits, start=1))
    #         2) слепете ги с празен ред между тях
    #         3) върнете "Контекст:\n<частите>\n\nВъпрос: <въпросът>"
    parts = []
    for i, h in enumerate(hits, start=1):
        parts.append(f"[{i}] {h}")
    context = "\n\n".join(parts)
    return f"Контекст:\n{context}\n\nВъпрос: {question}"
