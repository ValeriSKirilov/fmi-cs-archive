import ollama

EMBED_MODEL = "bge-m3"   # многоезичен, 1024 измерения (Тема 5); трябва да съвпада с db/init.sql

# Инструкцията, която кара модела да отговаря САМО от намерените части.
# Малкият локален модел (bggpt:4b) иска формата на отговора изрично: иначе той
# или отказва и при наличен отговор, или връща само „[2]“ без текст. Примерът е
# без съдържание („...“): пример с факт моделът копира в отговорите си.
GROUNDED_SYSTEM = (
    "Отговаряй само въз основа на предоставения контекст. Отговори с цяло изречение "
    "и след него посочи в квадратни скоби номера на частта, от която идва, "
    "напр. „... [2].“ Ако отговорът не се съдържа в контекста, кажи "
    "'Нямам достатъчно информация.'"
)

# За сравнение (флаг --no-grounding): без никакво ограничение.
PLAIN_SYSTEM = "Ти си полезен асистент. Отговаряй кратко, на български."


def embed(texts: list[str]) -> list[list[float]]:
    """Векторизира всички текстове с една заявка. (дадено)"""
    return ollama.embed(model=EMBED_MODEL, input=texts)["embeddings"]


def retrieve(store, question: str, k: int = 4):
    """RETRIEVE: векторизира въпроса със СЪЩИЯ модел и връща k-те най-близки части. (дадено)"""
    return store.query(embed([question])[0], top_k=k)


def build_prompt(question: str, hits) -> str:
    """AUGMENT: номериран контекст [1], [2], ... и въпросът след него."""
    context = "\n\n".join(f"[{i}] {h.text}" for i, h in enumerate(hits, start=1))
    return f"Контекст:\n{context}\n\nВъпрос: {question}"
