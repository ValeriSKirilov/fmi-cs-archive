from __future__ import annotations

from enum import Enum

from pydantic import BaseModel


class Tone(str, Enum):
    """Изброим тип: моделът може да върне САМО една от тези три стойности."""

    positive = "положително"
    negative = "отрицателно"
    neutral = "неутрално"


class Review(BaseModel):
    """Класификация на отзив. Ползва се от `01_extract.py --classify`."""

    tone: Tone
    reason: str


class Contact(BaseModel):
    """Контакт, извлечен от свободен текст."""

